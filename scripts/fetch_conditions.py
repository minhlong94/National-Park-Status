#!/usr/bin/env python3
"""Build data/road-conditions.js: the road condition tables that parks post on their conditions page (R51).

Some parks (for example Capitol Reef) keep a table "Road Name | Condition | Updated on" on
https://www.nps.gov/<code>/planyourvisit/conditions.htm, one table for each district. The NPS API does not have
this data, and a browser cannot read nps.gov pages, so this script reads the tables for all parks.

A table is used when its first row has a "Road" column and a "Condition" (or "Status") column.
The heading above the table (for example "Fruita Historic District") is the district name.

The workflow .github/workflows/update-conditions.yml runs this script every 6 hours.
"""
import datetime as dt
import html
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fetch_history as fh  # noqa: E402  (load_parks)

OUT = fh.ROOT / "data" / "road-conditions.js"
PAGES = ["planyourvisit/conditions.htm", "planyourvisit/road-conditions.htm", "planyourvisit/roads.htm"]


def get(url):
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"}), timeout=30) as r:
            if r.geturl().rstrip("/").endswith("/index.htm"):
                return None  # NPS sends a missing page to the park home page
            return r.read().decode("utf-8", "ignore")
    except Exception:  # noqa: BLE001
        return None


def clean(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s))).strip()


def tables(page):
    """[(heading, [[cell, ...], ...]), ...] for each table, with the last heading before it."""
    out = []
    for m in re.finditer(r"<table.*?</table>", page, flags=re.S | re.I):
        heads = re.findall(r"<h[2-5][^>]*>(.*?)</h[2-5]>", page[:m.start()], flags=re.S | re.I)
        rows = [[clean(c) for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", tr, flags=re.S | re.I)]
                for tr in re.findall(r"<tr.*?</tr>", m.group(0), flags=re.S | re.I)]
        out.append((clean(heads[-1]) if heads else "", [r for r in rows if any(r)]))
    return out


def road_tables(page):
    districts = []
    for head, rows in tables(page):
        if len(rows) < 2:
            continue
        h = [c.lower() for c in rows[0]]
        road = next((i for i, c in enumerate(h) if "road" in c), None)
        cond = next((i for i, c in enumerate(h) if "condition" in c or "status" in c), None)
        if road is None or cond is None or road == cond:
            continue
        date = next((i for i, c in enumerate(h) if "updated" in c or "date" in c), None)
        roads = []
        for r in rows[1:]:
            if len(r) <= max(road, cond) or not r[road] or not r[cond]:
                continue
            roads.append({"n": r[road], "c": r[cond], "d": r[date] if date is not None and date < len(r) else ""})
        if roads:
            districts.append({"name": head, "roads": roads})
    return districts


def main():
    parks = fh.load_parks()
    out = {"built": dt.datetime.utcnow().strftime("%Y-%m-%dT%H:%MZ"), "parks": {}}
    for code in sorted({p["code"] for p in parks}):
        for pg in PAGES:
            url = f"https://www.nps.gov/{code}/planyourvisit/{pg.split('/')[-1]}"
            page = get(url)
            if not page:
                continue
            d = road_tables(page)
            if d:
                m = re.search(r"(?i)road conditions? update[sd]? as of\s*([0-9/]+)", clean(page))
                out["parks"][code] = {"src": url, "asOf": m.group(1) if m else "", "districts": d}
                print(f"  {code}: {sum(len(x['roads']) for x in d)} roads in {len(d)} tables from {pg}", flush=True)
                break
        time.sleep(0.2)
    print("parks with road condition tables:", sorted(out["parks"]), flush=True)
    OUT.write_text("// Generated by scripts/fetch_conditions.py. Do not edit by hand.\n"
                   "// n = road, c = condition, d = date of the condition (as the park writes it).\n"
                   "window.PARK_ROADCOND = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n", encoding="utf-8")
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
